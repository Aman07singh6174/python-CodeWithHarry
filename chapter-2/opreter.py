# arithmetic
print(5 + 3)  # Addition
print(5 - 3)  # Subtraction
print(5 * 3)  # Multiplication
print(5 / 3)  # Division

#  ASSIGMENT
a = 5
print(a)  # Output: 5
a+= 3
print(a)  # Output: 8

# CAMARISON
print(5 == 3)  # Output: False
print(5 != 3)  # Output: True
print(5 > 3)   # Output: True
print(5 < 3)   # Output: False

# Logical operators
print(True and False)  # Output: False
print(True or False)   # Output: True
print(not True)        # Output: False